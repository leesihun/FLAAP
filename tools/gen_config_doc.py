"""Regenerate docs/CONFIGURATION.md from flaap.launcher.specs (single source of truth).

    python tools/gen_config_doc.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from flaap.launcher.parser import format_value  # noqa: E402
from flaap.launcher.specs import BASE_DEFAULTS, COMMON_KEYS, INDEXED_PATTERNS, ROUTES  # noqa: E402

HEAD = """# FLAAP configuration reference

> Generated by `python tools/gen_config_doc.py` from `flaap/launcher/specs.py`.
> Do not edit the per-route tables by hand.

FLAAP runs from flat `key value` text files in the AI-CAE4ALL style:

```text
% Goland wing flutter, DLM + PK
model        flutter          # route
mode         pk               # operation inside the route
structure    goland
mach         0.0
density      1.225
velocities   60, 260, 101     # start, stop, count [m/s]
```

```bash
python FLAAP_main.py --config configs/flutter/ex1/config_goland_pk.txt   # preflight + run
python FLAAP_main.py --config <cfg> --check            # preflight only
python FLAAP_main.py --config <cfg> --dry-run          # print resolved config, no solve
python FLAAP_main.py --config <cfg> --explain-config   # each key, value and its source
python FLAAP_main.py --config <cfg> --strict --json-report preflight.json
python FLAAP_main.py --list-models
python FLAAP_main.py --describe flutter
python FLAAP_main.py --audit-configs configs           # preflight every config_*.txt
python studio/start_studio.py                          # FLAAP Studio GUI
```

Exit codes: `0` success, `1` preflight errors, `2` usage error, `3` run failed.

## Grammar

| rule | detail |
|---|---|
| line | `key value`; the key is the first token, the rest of the line is the value |
| assignment | `key = value` and `key: value` are also accepted (notice `CFG-SYNTAX-003`) |
| comments | `%` at the start of a line; `#` anywhere starts an inline comment |
| lists | comma- or space-separated values, e.g. `velocities 60, 260, 101` |
| booleans | `true` / `false` (also `yes/no`, `on/off`) |
| case | keys and values are lower-cased except path keys and `title` |
| paths | relative to the config file's folder |
| duplicates | a key may appear once (`CFG-DUP-001`) |
| encoding | UTF-8 without BOM |

`model` selects the analysis route and `mode` the operation inside it. If `mode`
is omitted the route's first mode is used. Every key not listed for the chosen
route raises `CFG-KEY-001` with a spelling suggestion (a warning, an error under `--strict`).

## Preflight diagnostics

| code | meaning |
|---|---|
| CFG-FILE-001/003/005 | file missing / unreadable / BOM or encoding problem |
| CFG-SYNTAX-001/002 | line without value / malformed indexed key |
| CFG-DUP-001 | duplicate key |
| CFG-REQ-001..005 | required key missing (model, mode, route-specific keys, files, surfaces) |
| CFG-ROUTE-001..003 | unknown model / unknown mode / key group not valid for the route |
| CFG-KEY-001 | unknown key (with "did you mean") |
| CFG-TYPE-001 | value has the wrong type |
| CFG-VALUE-001..007 | value outside the allowed choices or count (007: gmsh file type, `group_thickness` pairs) |
| CFG-PATH-001/002/003/004 | referenced file does not exist / no Radioss mode VTK files or no `.frd` result blocks found / binary `.frd` / gmsh physical group not defined in the `.geo`/`.msh` |
| CFG-DEP-001 | an optional Python module the route needs is not installed (gmsh) |
| CFG-CONFLICT-001 | contradictory keys (e.g. `density` and `altitude`) |
| CFG-RANGE-001/002 | non-positive or out-of-range numbers |
| CFG-TSD-001 | TSD validity (Mach window, single surface, subsonic) |
| CFG-DEFAULT-001..003 | notice: a default value was applied |

Warnings marked *strict* become errors under `--strict`.

## Structure sources (`structure`)

| value | source | needs |
|---|---|---|
| goland | Goland wing beam FE (Euler-Bernoulli bending + torsion) | - |
| goland_ctrl | Goland wing with a trailing-edge aileron (60-100 % span, hinge 0.8c) | - |
| agard445 | AGARD 445.6 weakened model 3, orthotropic MITC4 plate | `experimental_frequencies` optional |
| demo_aircraft | free-free flexible demo aircraft (wing + tail, rigid-body modes) | - |
| plate | trapezoidal plate FE from planform + material | `plate_*`, `thickness`, `material` |
| nastran | MSC/NX Nastran SOL 103 `.f06` | `structure_file`, `surface1`, `bref` |
| ansys | ANSYS modal export (see `docs/OUTPUT_FORMAT.md`) | `structure_file`, `surface1`, `bref` |
| openradioss | OpenRadioss starter deck (`*_0000.rad`) -> FE model -> modes | `structure_file`, `surface1`, `bref` |
| openradioss_eig | Radioss `/EIG` modes: `anim_to_vtk` files `<run>A001.vtk ...` (folder, one file or engine listing) | `structure_file`; optional `bulk_file` (starter deck), `mode_files`, `frequency_file`, `radioss_units` |
| calculix | CalculiX `*FREQUENCY` results: ASCII `.frd` (DISP blocks, VALUE = Hz, unit modal mass) + optional `.dat` eigenvalue table | `structure_file`; optional `frequency_file` (`.dat`), `length_scale` / `mass_scale` (ccx has no unit system) |
| gmsh | gmsh mesher: `.geo` script (meshed with its own sizes / transfinite / Recombine), existing `.msh`, or STEP/IGES/BREP -> tri3/quad4 shells or tet4/tet10/hex8 solids -> clamped modes | `structure_file`, `thickness` (shells), material keys; `clamp_group` (physical group), `mesh_size`, `mesh_order`, `recombine`, `mesh_dim`, `mesh_algorithm`, `group_thickness`, `mesh_save` |
| geometry / stl | STL / STEP / IGES geometry + material -> shell or tetra FE -> modes | `structure_file`, material keys |
| legacy | original Fortran FLAAP deck folder (`LEE_input.txt`, `M_K.txt`, ...) | `structure_file` (folder) |

Materials: `aluminum` (71 GPa, 0.33, 2700 kg/m^3), `steel` (210 GPa, 0.30, 7850),
`titanium` (114 GPa, 0.34, 4430), `cfrp_quasi` (60 GPa, 0.30, 1600), or
`custom` with `young`, `poisson`, `material_density`.

## Indexed keys

"""


def _esc(t: str) -> str:
    return str(t).replace("|", "\|")


def route_section(name, spec) -> str:
    out = [f"## Route `{name}`", "", spec.description, "", "| mode | description |", "|---|---|"]
    for m, d in spec.modes.items():
        out.append(f"| `{m}` | {d} |")
    req = {m: r for m, r in spec.required_by_mode.items() if r}
    if req:
        out += ["", "Required keys: " + "; ".join(f"`{m}`: {', '.join(r)}" for m, r in req.items())]
    out += ["", "| key | type | default | description |", "|---|---|---|---|"]
    defaults = dict(BASE_DEFAULTS)
    defaults.update(spec.defaults)
    for grp in spec.key_groups:
        for k, (desc, typ) in grp.items():
            dv = defaults.get(k)
            dtxt = f"`{format_value(dv)}`" if dv is not None else ""
            out.append(f"| `{k}` | {typ} | {dtxt} | {_esc(desc)} |")
    return "\n".join(out) + "\n"


def main():
    parts = [HEAD]
    parts.append("| pattern | values |\n|---|---|")
    for k, (_, fields) in INDEXED_PATTERNS.items():
        parts.append(f"| `{k}N` | {fields} |")
    parts.append("\n`hinge` is the chord fraction of the hinge line, `eta0/eta1` the span fractions "
                 "of the control surface. Stations define load-recovery cuts (point + axis).\n")
    parts.append("## Keys common to every route\n\n| key | type | default | description |\n|---|---|---|---|")
    for k, (desc, typ) in COMMON_KEYS.items():
        dv = BASE_DEFAULTS.get(k)
        dtxt = f"`{format_value(dv)}`" if dv is not None else ""
        parts.append(f"| `{k}` | {typ} | {dtxt} | {_esc(desc)} |")
    parts.append("\nResults are written as key-value text files (`results.txt`, `modes.txt`, `flutter_*.txt`, ...); "
                 "see [OUTPUT_FORMAT.md](OUTPUT_FORMAT.md). `output_json true` also writes the JSON versions.\n")
    for name, spec in ROUTES.items():
        parts.append(route_section(name, spec))
    path = ROOT / "docs" / "CONFIGURATION.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(parts), encoding="utf-8")
    print("wrote", path)


if __name__ == "__main__":
    main()
